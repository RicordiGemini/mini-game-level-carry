/** 新手引导：一步 */
export interface TutorialStep {
    /** 卡片标题 */
    title: string;
    /** 卡片正文（支持 \n 换行） */
    body: string;
    /**
     * 可选按钮文案。不填 = 默认"下一步"。
     * 最后一步用它做 CTA（如「开始第 1 关」）。
     */
    cta?: string;
}

/** 首通教学：一张提示卡 */
