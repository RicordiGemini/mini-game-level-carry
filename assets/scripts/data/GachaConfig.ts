/**
 * 连续抽到"已拥有"多少个之后，下一抽必定给还没见过的。
 *
 * 【为什么需要保底，以及为什么定在 30 而不是 10】
 *   20 个可收集项、两个池子。武器池 12 项时，
 *   纯随机的期望抽到第 12 项新武器需要约 37 抽（收集问题里的"双生日"效应），
 *   尾部极长 —— 有玩家会连着 50 抽全是重复，体感就是"这游戏在坑我"。
 *
 *   定 30 的理由：
 *     - 30 抽 = 300 水晶，按普通难度算是 30 局、困难 10 局、噩梦 3 局，
 *       对应"认真打几天"，这是能被接受的等待长度。
 *     - 定 10 太短，等于每 10 抽必出一件新武器，
 *       收集感只剩 10 次，保底就不再是"兜底"而是"节奏"了。
 *
 * 计数器按**池子分别**累计且**只增不减**（拿到新东西就清零），
 * 于是"抽武器攒的保底"不会在抽辅助装备时被消耗掉。
 */
export const PITY_THRESHOLD = 30;

