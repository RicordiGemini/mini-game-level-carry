/**
 * 许愿抽卡配置表
 *
 * 【这一轮要解决的问题】
 *
 *   前六轮做完了玩法内容，但"武器怎么拿到"这件事一直是隐式的：
 *   EquipmentManager.syncProfile() 按关卡进度自动发放。
 *   玩家需求把它改成了明确的收集结构：
 *
 *     1. 每次通关给许愿水晶（普通 10 / 困难 30 / 噩梦 100）
 *     2. 10 个水晶抽一次
 *     3. 开局只给一把基础武器，其他全靠抽
 *     4. 局内三选一可以抽到**所有**武器与辅助（局内不设限）
 *     5. 武器池与辅助池**分开抽**
 *     6. 辅助装备可升阶，升阶提升基础加成
 *
 * 【为什么抽卡是"局外永久收藏"而不是"局内获取"的翻版】
 *
 *   局内三选一已经能拿到所有东西了（规则 4）。
 *   那抽卡的意义不在于"解锁新玩法"，而在于三条：
 *
 *     - **局外强度**：抽到的武器才有局外等级（可金币升级、可锻造突破、可镶属性），
 *       局内三选一拿到的武器永远是 1 级。一把满锻的稀有武器是打 50 局换来的，
 *       这个长期目标必须有一个"看得见的容器"来装 —— 就是抽卡。
 *     - **有选择的获得**：自动发放意味着"解锁第 3 关 = 必得长枪"，
 *       玩家没有期待感。抽卡给了"下一把是什么"这个悬念，
 *       而悬念本身就是留存。
 *     - **双池抉择**：武器池与辅助池分开，玩家要在"变强的方式"上做选择，
 *       而不是一把鼻涕一把泪全都要。
 *
 * 【三条不可让步的规则】
 *
 *   1. **没有任何一步需要看广告**。
 *      本文件与 GachaManager 的所有函数都不接收广告参数 —— 从接口上就不可能做出强制。
 *      广告至多是"看完给 10 水晶"这种可选加速（见 grantCrystalByAd）。
 *
 *   2. **重复件必须有用**。
 *      12 把武器 + 8 件辅助 = 20 个可收集项，保底再高也一定会重复。
 *      重复件一律转化为该装备的**专属锻造材料**（复用第四轮的材料背包），
 *      于是重复不是"白抽"，而是"这把的突破进度" ——
 *      这也顺带让抽卡与锻造两条线互相喂，形成正循环。
 *
 *   3. **抽卡不提供数值碾压**。
 *      抽到的武器是 1 级，基础伤害与自动发放时完全一致。
 *      抽卡的收益是"多一条可长期培养的线"，不是"立刻变强"。
 *      否则新号抽到一把枪就直接跳过前期的锻造积累，节奏全乱。
 */

/**
 * 许愿水晶的产出 —— 每次通关都给，按难度分档。
 *
 * 【为什么按难度给而不是给固定值】
 *   水晶是抽卡货币，也就是"下一把武器"的门票。
 *   如果普通难度也给 100，玩家会永远刷普通难度（10 抽 = 一把），
 *   难度阶梯的推进动机就被抽卡系统反向拆掉了。
 *
 *   普通 10 = 恰好一次单抽：通关一次，保证"每局都有小收获"，不至于空手。
 *   困难 30 = 三次单抽：这一档开始出现"能决定抽哪把"的选择空间。
 *   噩梦 100 = 一次十连：只有打通最难的那一档，才能一次拿到十个结果，
 *   于是噩梦难度除了"难"之外，还多了一个明确的追求目标。
 *
 * 与金币产出的区别：金币按 (关卡 × 难度 × 复玩) 派生并有复玩折扣，
 * 因为金币要防刷；水晶按**难度档固定发放、不打折**，
 * 因为它本身就是"通关"的奖励，打一次就该给足。
 */
export const CRYSTAL_REWARD_BY_TIER: number[] = [
    0,      // 索引 0 不使用
    10,     // 普通
    30,     // 困难
    100,    // 噩梦
];

/** 取某档难度通关获得的许愿水晶数量 */
export function crystalRewardOf(tier: number): number {
    const t = Math.max(1, Math.floor(tier || 1));
    const v = CRYSTAL_REWARD_BY_TIER[t];
    return v === undefined ? CRYSTAL_REWARD_BY_TIER[1] : v;
}

