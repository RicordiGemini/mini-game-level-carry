// ====================================================================
// 辅助装备升阶
// ====================================================================

/** 辅助装备最高阶 */
export const AUX_MAX_RANK = 5;

/**
 * 每一阶的升阶花费（金币）。
 *
 * 【升阶买的是什么】
 *   辅助装备原本是"纯局内"的 —— 打一局扔一局，没有长期投入。
 *   这一轮给了它局外阶数，于是它变成与武器对等的长期养成线：
 *   抽到 → 升阶 → 每局带着它进场时效果更强。
 *
 * 花费刻意**高于同阶武器升级**（武器升满 5 级约 200+900+1600+2300 合计 5000），
 * 因为辅助装备的阶数是**纯增益叠加**的，没有"进化"这种质变作为回报。
 * 曲线取 800 / 1800 / 3600 / 6800，合计 13000 —— 是一条要跨难度慢慢推的线。
 */
export const AUX_RANK_COST: number[] = [0, 800, 1800, 3600, 6800];

/**
 * 每一阶对**基础加成**的放大倍率。
 *
 * 【为什么是倍率而不是固定加值】
 *   辅助装备的 effect 结构各异（有的给 6 点荆棘，有的给 6% 暴击）。
 *   固定加值会让"数值型"辅助（荆棘 +34）随阶数变得平庸，
 *   而"百分比型"辅助（暴击 24%）又会线性爆炸。
 *   用倍率统一放大，两类都保持"抽到就变强"的体感，且不会破坏平衡：
 *
 *     阶 1 → 1.00（等于原值，兼容抽卡前的老数值）
 *     阶 2 → 1.25
 *     阶 3 → 1.55
 *     阶 4 → 1.90
 *     阶 5 → 2.30
 *
 *   终局 2.3 倍 ≈ 一件 depth 2 终局形态的强度，符合"抽到+满阶 = 长期主力"的位置。
 */
export const AUX_RANK_MUL: number[] = [0, 1.0, 1.25, 1.55, 1.90, 2.30];

/** 取某阶的加成倍率，越界收敛 */
export function auxRankMul(rank: number): number {
    const r = Math.max(1, Math.min(AUX_MAX_RANK, Math.floor(rank || 1)));
    const v = AUX_RANK_MUL[r];
    return v === undefined ? 1.0 : v;
}

/** 升到下一阶需要的金币，已满阶返回 -1 */
export function auxRankCost(rank: number): number {
    const r = Math.max(1, Math.floor(rank || 1));
    if (r >= AUX_MAX_RANK) return -1;
    const v = AUX_RANK_COST[r];
    return v === undefined ? AUX_RANK_COST[1] : v;
}

